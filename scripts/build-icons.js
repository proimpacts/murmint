'use strict';
const fs = require('fs');
const path = require('path');

const data = require('../src/renderer/assets/ui-icons/icons.json');
const svg = (body, size = 24) => `<svg class="ic" viewBox="0 0 ${size} ${size}" width="20" height="20" fill="currentColor" aria-hidden="true">${body}</svg>`;

// "name:on" = filled variant for the active tab
const icons = {};
for (const [key, v] of Object.entries(data)) {
  icons[key] = svg(v.r, v.s);
  if (v.f) icons[`${key}:on`] = svg(v.f, v.s);
}

const out = `// GENERATED by scripts/build-icons.js from Microsoft's Fluent System Icons (MIT). Do not edit by hand.
(function () {
  window.Icons = ${JSON.stringify(icons, null, 2)};
  window.icon = (n, cls) => { const t = document.createElement('span'); t.className = 'icw ' + (cls || ''); t.innerHTML = window.Icons[n] || window.Icons[String(n).replace(/:on$/, '')] || ''; return t; };
})();
`;
fs.writeFileSync(path.join(__dirname, '..', 'src', 'renderer', 'shared', 'icons.js'), out);
console.log('icons.js written with', Object.keys(icons).length, 'icons');
