'use strict';
const { contextBridge, ipcRenderer } = require('electron');

const invoke = (ch, ...a) => ipcRenderer.invoke(ch, ...a);
const on = (ch, fn) => {
  const h = (_e, p) => fn(p);
  ipcRenderer.on(ch, h);
  return () => ipcRenderer.removeListener(ch, h);
};

contextBridge.exposeInMainWorld('murmintIpc', {
  getState: () => invoke('state:get'),
  set: (path, value) => invoke('config:set', path, value),
  saveProvider: (p) => invoke('provider:save', p),
  removeProvider: (id) => invoke('provider:remove', id),
  setKey: (id, key) => invoke('provider:key', id, key),
  installedApps: () => invoke('apps:classic'),
  installedStoreApps: () => invoke('apps:store'),
  pickProgram: () => invoke('apps:pick'),
  testProvider: (id) => invoke('provider:test', id),
  providerPresets: () => invoke('provider:presets'),
  providerModels: (id) => invoke('provider:models', id),
  captureKeys: (on) => invoke('keys:capture', on),
  keysDown: () => invoke('keys:down'),
  clearHistory: () => invoke('history:clear'),
  installUpdate: () => invoke('update:install'),
  checkUpdate: () => invoke('update:check'),
  getUpdate: () => invoke('update:get'),
  deleteHistory: (id) => invoke('history:delete', id),
  copyText: (text) => invoke('clipboard:write', text),
  usage: () => invoke('usage:summary'),
  routerPreview: () => invoke('router:preview'),
  trainVocab: (take) => invoke('vocab:train', take),
  winAction: (a) => invoke('win:action', a),
  tryFormat: (opts) => invoke('format:try', opts),
  resetUsage: () => invoke('usage:reset'),
  session: (action) => invoke('session:action', action),
  undoInsert: () => invoke('session:undo'),
  sendSegment: (seg) => ipcRenderer.send('rec:segment', seg),
  sendPreview: (p) => invoke('rec:preview', p),
  recError: (message) => ipcRenderer.send('rec:error', message),
  sendChunk: (buf) => ipcRenderer.send('rec:chunk', buf),
  sendBoundary: (b) => ipcRenderer.send('rec:boundary', b),
  sendAutoStop: () => ipcRenderer.send('rec:autostop'),
  overlayHover: (hovering) => ipcRenderer.send('overlay:hover', hovering),
  overlayDrag: (phase, p) => ipcRenderer.send('overlay:drag', phase, p),
  overlayPin: (on) => ipcRenderer.send('overlay:pin', on),
  account: () => invoke('account:get'),
  signIn: () => invoke('account:signIn'),
  cancelSignIn: () => invoke('account:cancel'),
  signOut: () => invoke('account:signOut'),
  onboarding: () => invoke('onboarding:get'),
  finishOnboarding: (setup) => invoke('onboarding:finish', setup),
  localModels: () => invoke('local:status'),
  downloadModels: () => invoke('local:download'),
  cancelModels: () => invoke('local:cancel'),
  clipboardItems: () => invoke('clipboard:list'),
  clipboardPick: (what) => invoke('clipboard:pick', what),
  clipboardPin: (id) => invoke('clipboard:pin', id),
  clipboardRemove: (id) => invoke('clipboard:remove', id),
  clipboardClear: () => invoke('clipboard:clear'),
  clipboardClose: () => invoke('clipboard:close'),
  clipboardDrag: (on) => invoke('clipboard:drag', on),
  setBetterClipboard: (on) => invoke('clipboard:enable', on),
  startModels: () => invoke('local:start'),
  appIcon: (exe) => invoke('app:icon', exe),
  siteIcon: (host) => invoke('site:icon', host),
  on,
  platform: process.platform,
});
